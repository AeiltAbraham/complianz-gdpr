/**
 * ADR-009 vendor CSS pipeline (T-056). For each manifest entry it reads a committed
 * settings/src/styles/vendors/<name>.src.css (which @imports the library's upstream stylesheet(s) plus our
 * token-literal overrides), inlines the imports (postcss-import), scopes EVERY selector to the widget's
 * data-cmplz-isolate zone (postcss-prefix-selector, mapping :root/html/body -> the zone element so the
 * library's document-level styles land on the zone), and emits in-file [dir=rtl] variants (postcss-rtlcss) —
 * writing a GENERATED, gitignored <name>.built.css that tailwind.css @imports and the entry pipeline's
 * postcss-import then inlines into the single build/index.css.
 *
 * Build-time only (the two plugins are never shipped). Runs via `npm run build:vendors`, prepended to
 * `build`/`start`. The generated *.built.css is gitignored (ADR-006 — build output is never committed);
 * source of truth = the committed .src.css + this script. preview.css and data-table.css are hand-scoped /
 * overrides-only and are NOT in the manifest, so they are never re-processed (they stay their own direct
 * @imports in tailwind.css). Mirrors the CommonJS convention of scripts/check-physical-utilities.js.
 */
const fs = require( 'fs' );
const path = require( 'path' );
const postcss = require( 'postcss' );
const atImport = require( 'postcss-import' );
const prefixer = require( 'postcss-prefix-selector' );
// postcss-rtlcss is published as a default export (ESM interop).
const rtlcss = require( 'postcss-rtlcss' ).default || require( 'postcss-rtlcss' );

const VENDORS_DIR = path.join( __dirname, '..', 'src', 'styles', 'vendors' );

// One row per auto-scoped vendor (a library that ships upstream CSS AND renders inside #complianz).
// react-shepherd is NOT here: it mounts at document.body, so the #complianz-descendant scope would be
// dead CSS — it is hand-scoped in vendors/shepherd.css instead (ADR-009 Option B, T-058).
const MANIFEST = [
	{ src: 'date-range.src.css', zone: 'date-range' },
	{ src: 'toast.src.css', zone: 'toastify' },
];

async function buildOne( { src, zone } ) {
	const srcPath = path.join( VENDORS_DIR, src );
	const outPath = srcPath.replace( /\.src\.css$/, '.built.css' );
	const css = fs.readFileSync( srcPath, 'utf8' );
	const prefix = `:is(#complianz, #complianz-portal) [data-cmplz-isolate="${ zone }"]`;
	const result = await postcss( [
		atImport(),
		prefixer( {
			prefix,
			// Document-root selectors carry the library's doc-level styles/custom-props -> land them on the zone
			// element; @keyframes names are left untouched by prefix-selector so animation-name refs resolve.
			transform( pfx, selector, prefixedSelector ) {
				return selector === ':root' || selector === 'html' || selector === 'body'
					? pfx
					: prefixedSelector;
			},
		} ),
		// `override` (not the default `combined`): keep the full LTR styling in the UNPREFIXED base rule
		// (so it applies in the default WordPress admin, which carries NO dir attribute — WP only sets
		// dir="rtl" under is_rtl()) and add [dir="rtl"] overrides on top. `combined` emits directional
		// props under [dir="ltr"]/[dir="rtl"] only, so every directional rule would be dead in the
		// dir-less LTR admin (the primary locale). override also zeroes the flipped-away side in the RTL
		// variant, so there is no double-application. (T-056 review finding; verified against the pipeline.)
		rtlcss( { mode: 'override' } ),
	] ).process( css, { from: srcPath, to: outPath } );
	const banner = `/* GENERATED by scripts/build-vendor-css.js from ${ src } (zone="${ zone }") — DO NOT EDIT; gitignored (ADR-006/ADR-009). */\n`;
	fs.writeFileSync( outPath, banner + result.css );
	console.log(
		`build-vendor-css: ${ src } -> ${ path.basename( outPath ) } (${ result.css.length } bytes, zone=${ zone })`
	);
}

( async () => {
	for ( const entry of MANIFEST ) {
		await buildOne( entry );
	}
} )().catch( ( e ) => {
	console.error( 'build-vendor-css failed:', e );
	process.exit( 1 );
} );
